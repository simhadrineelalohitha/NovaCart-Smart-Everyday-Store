const path = require('path');
const fs = require('fs');
const dotenv = require('dotenv');

dotenv.config({ path: path.resolve(__dirname, '../../.env') });
dotenv.config({ path: path.resolve(__dirname, '../.env') });

const isPostgres = Boolean(process.env.DATABASE_URL);
if (process.env.NODE_ENV === 'production' && !isPostgres) {
  throw new Error('DATABASE_URL is required in production; refusing to open a local SQLite database.');
}

let pool;
let sqlite;
let sqliteTransactionQueue = Promise.resolve();

if (isPostgres) {
  const { Pool } = require('pg');
  pool = new Pool({
    connectionString: process.env.DATABASE_URL,
    ssl: process.env.NODE_ENV === 'production'
      ? { rejectUnauthorized: process.env.PGSSL_REJECT_UNAUTHORIZED === 'false' ? false : true }
      : undefined,
  });
} else {
  const Database = require('better-sqlite3');
  const dbPath = path.resolve(__dirname, '..', process.env.DB_PATH || './novacart.db');
  sqlite = new Database(dbPath);
  sqlite.pragma('foreign_keys = ON');
  console.log('SQLite connected:', dbPath);
}

function postgresSql(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

function sqliteQuery(connection, sql, params) {
  const statement = connection.prepare(sql);
  if (statement.reader) {
    const rows = statement.all(...params);
    return { rows, rowCount: rows.length };
  }

  const result = statement.run(...params);
  return { rows: [], rowCount: result.changes, changes: result.changes };
}

async function query(sql, params = []) {
  if (isPostgres) return pool.query(postgresSql(sql), params);

  const available = sqliteTransactionQueue;
  await available;
  return sqliteQuery(sqlite, sql, params);
}

async function withTransaction(callback) {
  if (isPostgres) {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const result = await callback({
        query: (sql, params = []) => client.query(postgresSql(sql), params),
      });
      await client.query('COMMIT');
      return result;
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    } finally {
      client.release();
    }
  }

  const previous = sqliteTransactionQueue;
  let release;
  sqliteTransactionQueue = new Promise(resolve => { release = resolve; });
  await previous;
  let transactionStarted = false;
  try {
    sqlite.exec('BEGIN IMMEDIATE');
    transactionStarted = true;
    const result = await callback({ query: async (sql, params = []) => sqliteQuery(sqlite, sql, params) });
    sqlite.exec('COMMIT');
    return result;
  } catch (error) {
    if (transactionStarted) sqlite.exec('ROLLBACK');
    throw error;
  } finally {
    release();
  }
}

async function testConnection() {
  await query('SELECT 1');
  return true;
}

async function ensureSchema() {
  if (isPostgres) {
    await pool.query(`
      ALTER TABLE users ADD COLUMN IF NOT EXISTS role TEXT NOT NULL DEFAULT 'user';
      ALTER TABLE users ADD COLUMN IF NOT EXISTS google_sub TEXT;
      ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_url TEXT;
      ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;
      ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('user', 'admin'));
      CREATE UNIQUE INDEX IF NOT EXISTS users_google_sub_key ON users (google_sub) WHERE google_sub IS NOT NULL;
      CREATE TABLE IF NOT EXISTS wishlist_items (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        UNIQUE (user_id, product_id)
      );
      CREATE TABLE IF NOT EXISTS compare_items (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        UNIQUE (user_id, product_id)
      );
      ALTER TABLE orders ADD COLUMN IF NOT EXISTS shipping_name TEXT;
      ALTER TABLE orders ADD COLUMN IF NOT EXISTS shipping_address TEXT;
      ALTER TABLE orders ADD COLUMN IF NOT EXISTS shipping_phone TEXT;
    `);
    return;
  }

  sqlite.exec(fs.readFileSync(path.join(__dirname, '../models/schema.sqlite.sql'), 'utf8'));
  const columns = sqlite.prepare('PRAGMA table_info(users)').all();
  if (!columns.some(column => column.name === 'role')) sqlite.exec("ALTER TABLE users ADD COLUMN role TEXT NOT NULL DEFAULT 'user'");
  if (!columns.some(column => column.name === 'google_sub')) sqlite.exec('ALTER TABLE users ADD COLUMN google_sub TEXT');
  if (!columns.some(column => column.name === 'avatar_url')) sqlite.exec('ALTER TABLE users ADD COLUMN avatar_url TEXT');
  sqlite.exec('CREATE UNIQUE INDEX IF NOT EXISTS users_google_sub_key ON users (google_sub) WHERE google_sub IS NOT NULL');
  const orderColumns = new Set(sqlite.prepare('PRAGMA table_info(orders)').all().map(column => column.name));
  for (const column of ['shipping_name', 'shipping_address', 'shipping_phone']) {
    if (!orderColumns.has(column)) sqlite.exec(`ALTER TABLE orders ADD COLUMN ${column} TEXT`);
  }
}

async function close() {
  if (pool) await pool.end();
  if (sqlite) sqlite.close();
}

module.exports = { isPostgres, query, withTransaction, testConnection, ensureSchema, close };
